// Pantalla provisoria: se reemplaza cuando se defina qué ajustes lleva (tema, moneda, unidades, etc.,
// TR-08). Lo que ya guarda SettingsRepository (tema y duración por defecto de una tarea) funciona sin pantalla.
// Es un destino secundario (se abre desde "Hoy", ticket 0025): lleva flecha para volver, como Rutinas.
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SettingsScreen(onBack: () -> Unit, modifier: Modifier = Modifier) {
    Scaffold(
        modifier = modifier,
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.nav_settings)) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = stringResource(R.string.action_close))
                    }
                }
            )
        }
    ) { innerPadding ->
        Box(Modifier.fillMaxSize().padding(innerPadding), contentAlignment = Alignment.Center) {
            Text(text = stringResource(R.string.nav_settings))
        }
    }
}
